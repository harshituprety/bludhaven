  mountain: ['bedroomWood', 'livingRoomCosy', 'kitchenRustic', 'deck', 'bedroom', 'diningTable', 'bathroom', 'livingRoom'],
  beach: ['bedroom', 'livingRoom', 'kitchen', 'pool', 'bathroomRain', 'diningTable', 'deck', 'balconyCity'],
