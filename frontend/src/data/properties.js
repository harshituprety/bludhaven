  lake: ['bedroomHeritage', 'livingRoom', 'kitchen', 'bathroom', 'backwaterDeck', 'balconyCity', 'courtyard', 'diningTable'],
  desert: ['bedroomHeritage', 'livingRoomHeritage', 'courtyard', 'rooftop', 'tentInterior', 'bathroom', 'deck', 'diningTable'],
